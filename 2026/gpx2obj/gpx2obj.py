def read_gpx(path):
    """Возвращает список (lat, lon, ele) по всем trkpt всех треков/сегментов."""
    tree = ET.parse(path)
    root = tree.getroot()
    pts = []
    for trkpt in root.iter():
        tag = trkpt.tag.rsplit('}', 1)[-1]
        if tag != 'trkpt':
            continue
        lat = float(trkpt.attrib['lat'])
        lon = float(trkpt.attrib['lon'])
        ele = 0.0
        for child in trkpt:
            if child.tag.rsplit('}', 1)[-1] == 'ele' and child.text:
                ele = float(child.text)
                break
        pts.append((lat, lon, ele))
    return pts


