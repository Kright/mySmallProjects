def meters_per_degree(lat_deg):
    """Метров в градусе широты и долготы на данной широте (WGS84, ряд)."""
    phi = math.radians(lat_deg)
    m_lat = (111132.954
             - 559.822 * math.cos(2 * phi)
             + 1.175 * math.cos(4 * phi))
    m_lon = (111412.84 * math.cos(phi)
             - 93.5 * math.cos(3 * phi)
             + 0.118 * math.cos(5 * phi))
    return m_lat, m_lon


class FlatProjection:
    def __init__(self, lat0, lon0, ele_offset=0.0):
        self.lat0 = lat0
        self.lon0 = lon0
        self.ele_offset = ele_offset
        self.m_lat, self.m_lon = meters_per_degree(lat0)

    def to_enu(self, lat, lon, ele):
        """-> (east, north, up) в метрах."""
        e = (lon - self.lon0) * self.m_lon
        n = (lat - self.lat0) * self.m_lat
        u = ele - self.ele_offset
        return e, n, u


def enu_to_obj(e, n, u, z_up):
    if z_up:
        return e, n, u          # X=восток, Y=север, Z=вверх
    return e, u, -n             # X=восток, Y=вверх, Z=юг


def dedupe(enu_pts, min_step):
    """Убирает подряд идущие точки ближе min_step (в горизонтальной плоскости)."""
    if min_step <= 0 or not enu_pts:
        return list(enu_pts)
    out = [enu_pts[0]]
    for p in enu_pts[1:]:
        q = out[-1]
        if math.hypot(p[0] - q[0], p[1] - q[1]) >= min_step:
            out.append(p)
    return out


