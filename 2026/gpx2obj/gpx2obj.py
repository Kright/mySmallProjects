#!/usr/bin/env python3
"""
gpx2obj.py -- превращает GPX-трек в Wavefront OBJ.

Два режима:
  --mode waypoints  -> вершины в точках центра дороги (элементы `p`, опционально ломаная `l`)
  --mode road       -> непрерывный меш дороги (лента с общими вершинами), машина едет
                       по центру. Ширина --width на прямых, в крутых поворотах плавно
                       растёт до --width-max (уширение проезжей части в кривых).
                       С --rects: старый вариант, независимые прямоугольники на отрезок.

Система координат:
  * центр (--lat0/--lon0) -> начало координат;
  * земля плоская: метров на градус широты/долготы считается один раз по широте центра;
  * OBJ: X = восток, Y = вверх (высота), Z = юг (правая тройка, Y-up).
    С флагом --z-up: X = восток, Y = север, Z = вверх.

Только стандартная библиотека.
"""

