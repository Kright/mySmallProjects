def output_name(src, mode, width, outdir):
    stem = os.path.splitext(os.path.basename(src))[0]
    if mode == 'waypoints':
        suffix = 'waypoints'
    else:
        suffix = 'road%d' % round(width * 10)   # 3.5 -> road35
    return os.path.join(outdir or os.path.dirname(src) or '.', '%s-%s.obj' % (stem, suffix))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('gpx', nargs='+', help='входные GPX-файлы')
    ap.add_argument('--mode', choices=['waypoints', 'road'], required=True)
    ap.add_argument('--lat0', type=float, default=LAT0, help='широта центра (default %(default)s)')
    ap.add_argument('--lon0', type=float, default=LON0, help='долгота центра (default %(default)s)')
    ap.add_argument('--ele-offset', type=float, default=0.0,
                    help='вычесть из высоты (по умолчанию высота абсолютная)')
    ap.add_argument('--width', type=float, default=WIDTH,
                    help='ширина дороги на прямой, м (default %(default)s)')
    ap.add_argument('--width-max', type=float, default=WIDTH_MAX,
                    help='ширина в самом крутом повороте, м (default %(default)s)')
    ap.add_argument('--r-narrow', type=float, default=R_NARROW,
                    help='радиус, от которого уширения уже нет, м (default %(default)s)')
    ap.add_argument('--r-wide', type=float, default=R_WIDE,
                    help='радиус, при котором ширина = --width-max, м (default %(default)s)')
    ap.add_argument('--step', type=float, default=STEP,
                    help='road: шаг пересэмплирования трека, м (default %(default)s)')
    ap.add_argument('--smooth', type=float, default=SMOOTH,
                    help='road: окно сглаживания геометрии, м (default %(default)s)')
    ap.add_argument('--curv-span', type=float, default=CURV_SPAN,
                    help='road: плечо оценки радиуса кривизны, м (default %(default)s)')
    ap.add_argument('--width-smooth', type=float, default=WIDTH_SMOOTH,
                    help='road: окно сглаживания ширины / длина отгона, м (default %(default)s)')
    ap.add_argument('--smooth-z', type=float, default=SMOOTH_Z,
                    help='road: окно сглаживания высоты, м (default %(default)s)')
    ap.add_argument('--jump', type=float, default=JUMP,
                    help='road: порог бокового скачка GNSS, м (default %(default)s)')
    ap.add_argument('--jump-z', type=float, default=JUMP_Z,
                    help='road: порог скачка высоты, м (default %(default)s)')
    ap.add_argument('--jump-blend', type=float, default=JUMP_BLEND,
                    help='road: длина сшивки бокового скачка, м (default %(default)s)')
    ap.add_argument('--jump-blend-z', type=float, default=JUMP_BLEND_Z,
                    help='road: длина сшивки скачка высоты, м (default %(default)s)')
    ap.add_argument('--glitch', type=float, default=GLITCH,
                    help='road: макс. длина глитча (скачок туда-обратно), который вырезается, м '
                         '(default %(default)s)')
    ap.add_argument('--min-step', type=float, default=None,
                    help='выкидывать подряд идущие точки ближе этого расстояния, м '
                         '(default: 0 для waypoints, 0.2 для road)')
    ap.add_argument('--rects', action='store_true',
                    help='road: независимые прямоугольники по сырым точкам вместо непрерывной ленты '
                         '(без уширения и сглаживания)')
    ap.add_argument('--polyline', action='store_true',
                    help='waypoints: добавить ломаную `l` через все точки')
    ap.add_argument('--z-up', action='store_true', help='оси X=восток Y=север Z=вверх')
    ap.add_argument('-o', '--outdir', default=None, help='каталог для .obj (default: рядом с gpx)')
    args = ap.parse_args(argv)

    if args.min_step is None:
        args.min_step = 0.0 if args.mode == 'waypoints' else 0.2

    proj = FlatProjection(args.lat0, args.lon0, args.ele_offset)
    if args.outdir:
        os.makedirs(args.outdir, exist_ok=True)

    for src in args.gpx:
        raw = read_gpx(src)
        if not raw:
            print('%s: нет trkpt, пропускаю' % src, file=sys.stderr)
            continue
        enu = [proj.to_enu(*p) for p in raw]
        pts = dedupe(enu, args.min_step)
        dst = output_name(src, args.mode, args.width, args.outdir)
        with open(dst, 'w') as f:
            write_header(f, src, args.mode, proj, args, len(raw), len(pts))
            if args.mode == 'waypoints':
                write_waypoints(f, pts, args.z_up, args.polyline)
                info = '%d points' % len(pts)
            else:
                if args.rects:
                    faces = write_road_rects(f, pts, args.width, args.z_up)
                    info = '%d points, %d quads (rects)' % (len(pts), faces)
                else:
                    rpts, widths, kappas, st = prepare_road(pts, args)
                    faces, clamped = write_road_strip(f, rpts, widths, args.z_up)
                    kmax = max(kappas) if kappas else 0.0
                    rmin = 1.0 / kmax if kmax > 0 else float('inf')
                    n_wide = sum(1 for w in widths if w > args.width + 0.05)
                    info = ('%d quads, width %.2f..%.2f m, min R %.0f m, widened %d of %d m, '
                            'jumps blended %d, glitch pts cut %d, z-drift pts %d, inner clamps %d'
                            % (faces, min(widths), max(widths), rmin,
                               round(n_wide * args.step), round(len(rpts) * args.step),
                               st['jumps'], st['glitch_pts'], st['drift_pts'], clamped))
        print('%s -> %s  (%s)' % (os.path.basename(src), os.path.basename(dst), info))


if __name__ == '__main__':
    main()
